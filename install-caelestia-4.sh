#!/usr/bin/env bash
# Caelestia Shell + Hyprland: установка стабильной версии на Arch Linux.
# Запускать от обычного пользователя, НЕ от root.
set -Eeuo pipefail
IFS=$'\n\t'
umask 077

LOG="$HOME/caelestia-setup.log"
STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="$HOME/.local/state/caelestia-backups/$STAMP"
WORKDIR=""
info(){ printf '\033[1;34m[INFO]\033[0m %s\n' "$*"; }
ok(){ printf '\033[1;32m[ OK ]\033[0m %s\n' "$*"; }
warn(){ printf '\033[1;33m[WARN]\033[0m %s\n' "$*"; }
die(){ printf '\033[1;31m[ERROR]\033[0m %s\n' "$*" >&2; exit 1; }
is_installed(){ pacman -Qq "$1" >/dev/null 2>&1; }

mkdir -p "$(dirname "$LOG")"
exec > >(tee -a "$LOG") 2>&1
trap 'rc=$?; printf "[ERROR] Сбой на строке %s (код %s). Лог: %s\n" "$LINENO" "$rc" "$LOG" >&2' ERR
trap 'if [[ -n "$WORKDIR" && -d "$WORKDIR" ]]; then rm -rf -- "$WORKDIR"; fi' EXIT

check_system(){
  [[ "$EUID" -ne 0 ]] || die 'Не запускайте через sudo; запустите от обычного пользователя.'
  [[ -r /etc/os-release ]] || die 'Не найден /etc/os-release.'
  # shellcheck disable=SC1091
  source /etc/os-release
  [[ "${ID:-}" == arch || " ${ID_LIKE:-} " == *" arch "* ]] || die 'Нужен Arch Linux или совместимый дистрибутив.'
  command -v pacman >/dev/null || die 'pacman не найден.'
  command -v sudo >/dev/null || die 'sudo не найден.'
  sudo -v
}
backup_user_path(){
  local src="$1" rel
  [[ -e "$src" || -L "$src" ]] || return 0
  mkdir -p "$BACKUP_DIR"
  rel="${src#"$HOME"/}"; rel="${rel//\//__}"
  cp -a -- "$src" "$BACKUP_DIR/$rel"
  ok "Резервная копия: $src"
}
check_state(){
  echo '=== Пакеты Caelestia / Quickshell ==='
  pacman -Q | grep -E '^(caelestia|quickshell|qs-)' || true
  echo; echo '=== Тема SDDM ==='
  grep -R -E '^[[:space:]]*Current=' /etc/sddm.conf /etc/sddm.conf.d 2>/dev/null || true
  echo; echo '=== Флаг autogenerated в Hyprland ==='
  grep -n 'autogenerated' "$HOME/.config/hypr/hyprland.lua" 2>/dev/null || true
  echo; echo '=== Автозапуск Caelestia ==='
  grep -R -n 'CAELESTIA SETUP\|caelestia shell' "$HOME/.config/hypr" 2>/dev/null || true
}

case "${1:-}" in
  --check) check_system; check_state; exit 0 ;;
  --rollback)
    check_system
    echo "Резервные копии: $HOME/.local/state/caelestia-backups"
    find "$HOME/.local/state/caelestia-backups" -mindepth 1 -maxdepth 2 -print 2>/dev/null | sort || true
    warn 'Автоматическое восстановление не выполняется, чтобы не затереть новые настройки.'
    exit 0 ;;
  ''|--clean-reinstall) ;;
  *) die "Использование: bash $0 [--check|--rollback|--clean-reinstall]" ;;
esac
CLEAN=false
[[ "${1:-}" != --clean-reinstall ]] || CLEAN=true
check_system

echo '=================================================='
echo ' Caelestia Shell — СТАБИЛЬНАЯ установка'
echo '=================================================='
info "Лог: $LOG"
info "Резервные копии: $BACKUP_DIR"
for p in \
  "$HOME/.config/caelestia" "$HOME/.config/hypr" \
  "$HOME/.config/autostart/caelestia.desktop" \
  "$HOME/.local/bin/restart-caelestia.sh"; do backup_user_path "$p"; done

if [[ "$CLEAN" == true && -d "$HOME/.config/caelestia" ]]; then
  warn 'Чистая переустановка: каталог настроек Caelestia будет перемещён в резервную копию.'
  mkdir -p "$BACKUP_DIR"
  mv -- "$HOME/.config/caelestia" "$BACKUP_DIR/caelestia-config-clean-reinstall"
fi

info 'Обновление Arch Linux и установка инструментов.'
sudo pacman -Syu --needed git base-devel curl jq
if ! command -v yay >/dev/null 2>&1; then
  info 'Устанавливаем yay из AUR.'
  WORKDIR="$(mktemp -d -t caelestia-yay.XXXXXXXX)"
  git clone --depth 1 https://aur.archlinux.org/yay.git "$WORKDIR/yay"
  (cd "$WORKDIR/yay" && makepkg -si --needed)
fi
command -v yay >/dev/null || die 'Не удалось установить yay.'

# Системные зависимости из официальных репозиториев. Не найденные в текущем
# выпуске пакеты пропускаются; существующие конфигурации не перезаписываются.
PACMAN_PACKAGES=(
  hyprland xdg-desktop-portal-hyprland qt6-wayland qt5-wayland
  polkit-kde-agent gnome-keyring networkmanager bluez bluez-utils
  pipewire pipewire-pulse pipewire-alsa pipewire-jack wireplumber
  sddm kitty fish starship fastfetch btop micro thunar firefox
  ttf-jetbrains-mono-nerd noto-fonts noto-fonts-cjk noto-fonts-emoji
  papirus-icon-theme adw-gtk-theme wl-clipboard cliphist lazygit bat
  ripgrep ydotool hyprpicker xdg-user-dirs trash-cli eza zoxide direnv foot
  brightnessctl ddcutil lm_sensors
)
for pkg in "${PACMAN_PACKAGES[@]}"; do
  if is_installed "$pkg"; then ok "$pkg уже установлен"
  elif pacman -Si "$pkg" >/dev/null 2>&1; then
    info "Устанавливаем пакет: $pkg"
    sudo pacman -S --needed "$pkg"
  else warn "Пакет $pkg не найден в официальных репозиториях; пропускаем."; fi
done

# Удаляем именно Git-сборки Caelestia и их debug-пакеты, которые вызвали
# конфликт файлов caelestia-shell-debug. Не используем -Rns/-Rdd.
GIT_PACKAGES=(caelestia-shell-git caelestia-shell-git-debug caelestia-cli-git caelestia-cli-git-debug)
found=()
for pkg in "${GIT_PACKAGES[@]}"; do is_installed "$pkg" && found+=("$pkg"); done
if ((${#found[@]})); then
  warn 'Найдены Git-пакеты Caelestia:'
  printf '  - %s\n' "${found[@]}"
  echo 'Будут удалены только эти пакеты командой pacman -R; зависимости автоматически не каскадируются.'
  read -r -p 'Удалить их и продолжить? [y/N] ' answer
  [[ "$answer" =~ ^[YyДд]$ ]] || die 'Отменено пользователем; Git-пакеты не удалены.'
  sudo pacman -R "${found[@]}"
else ok 'Git-пакеты Caelestia не обнаружены.'; fi

# Устанавливаем только стабильные пакеты. quickshell-git отдельно не удаляем:
# AUR-метаданные caelestia-shell определят необходимую версию Quickshell.
yay -Si caelestia-shell >/dev/null 2>&1 || die 'Стабильный caelestia-shell не найден в AUR; Git-версия устанавливаться не будет.'
info 'Устанавливаем стабильную Caelestia Shell.'
yay -S --needed caelestia-shell
if yay -Si caelestia-cli >/dev/null 2>&1; then
  info 'Устанавливаем стабильный Caelestia CLI.'
  yay -S --needed caelestia-cli
else warn 'Отдельный пакет caelestia-cli не найден; проверим команду после установки оболочки.'; fi
is_installed caelestia-shell || die 'pacman не подтвердил установку caelestia-shell.'
for pkg in "${GIT_PACKAGES[@]}"; do is_installed "$pkg" && die "$pkg всё ещё установлен; остановка."; done
ok 'Стабильная caelestia-shell установлена, Git-сборки Caelestia удалены.'

mkdir -p "$HOME/.config/caelestia" "$HOME/.config/hypr" "$HOME/.config/autostart" "$HOME/.local/bin"

# Применяем визуальный профиль в духе скриншота: стеклянные полупрозрачные
# панели, Dashboard с погодой/медиа/ресурсами и погода для Черкасска.
# Настройки пользователя сохраняются: jq выполняет рекурсивное объединение.
SHELL_JSON="$HOME/.config/caelestia/shell.json"
if command -v jq >/dev/null 2>&1; then
  THEME_TMP="$(mktemp)"
  if [[ -f "$SHELL_JSON" ]]; then
    if ! jq -e 'type == "object"' "$SHELL_JSON" >/dev/null 2>&1; then
      warn "$SHELL_JSON не является корректным JSON-объектом; оставляем его без изменений."
      rm -f -- "$THEME_TMP"
    else
      jq -s '.[0] * .[1]' "$SHELL_JSON" <(cat <<'THEMEJSON'
{
  "appearance": {"transparency": {"enabled": true, "base": 0.86, "layers": 0.42}},
  "dashboard": {"enabled": true, "showDashboard": true, "showMedia": true, "showPerformance": true, "showWeather": true},
  "services": {"weatherLocation": "Cherkessk,RU", "useFahrenheit": false, "useTwelveHourClock": false},
  "paths": {"wallpaperDir": "~/Pictures/Wallpapers"}
}
THEMEJSON
) > "$THEME_TMP" && cp -- "$THEME_TMP" "$SHELL_JSON" && ok 'Применён профиль Caelestia Glass: прозрачность, Dashboard, погода Черкасска.'
      rm -f -- "$THEME_TMP"
    fi
  else
    cat > "$THEME_TMP" <<'THEMEJSON'
{
  "appearance": {"transparency": {"enabled": true, "base": 0.86, "layers": 0.42}},
  "dashboard": {"enabled": true, "showDashboard": true, "showMedia": true, "showPerformance": true, "showWeather": true},
  "services": {"weatherLocation": "Cherkessk,RU", "useFahrenheit": false, "useTwelveHourClock": false},
  "paths": {"wallpaperDir": "~/Pictures/Wallpapers"}
}
THEMEJSON
    jq empty "$THEME_TMP" && install -m 600 "$THEME_TMP" "$SHELL_JSON" && ok 'Создан профиль Caelestia Glass: прозрачность, Dashboard, погода Черкасска.'
    rm -f -- "$THEME_TMP"
  fi
else
  warn 'jq не найден; профиль оформления не применён.'
fi

# Убираем только флаг автогенерированного конфига, если строка точно совпадает.
# Весь остальной hyprland.lua сохраняется без изменений.
HYPR_LUA="$HOME/.config/hypr/hyprland.lua"
if [[ -f "$HYPR_LUA" ]] && grep -Eq 'hl\.config\([[:space:]]*\{[[:space:]]*autogenerated[[:space:]]*=[[:space:]]*true[[:space:]]*\}[[:space:]]*\)' "$HYPR_LUA"; then
  sed -i -E '/hl\.config\([[:space:]]*\{[[:space:]]*autogenerated[[:space:]]*=[[:space:]]*true[[:space:]]*\}[[:space:]]*\)/d' "$HYPR_LUA"
  ok 'Убрана строка autogenerated = true из hyprland.lua.'
else info 'Флаг autogenerated в hyprland.lua не найден в ожидаемом формате; файл не менялся.'; fi

# Поддерживаем существующий формат конфигурации. Не создаём hyprland.conf,
# если пользователь уже работает на Lua-конфиге.
HYPR_CONF="$HOME/.config/hypr/hyprland.conf"
if [[ -f "$HYPR_LUA" ]]; then
  # На твоей системе используется Lua-конфиг Hyprland; используем тот же API,
  # который уже присутствует в шаблоне (hl.on / hl.exec_cmd).
  if ! grep -Fq -- '-- BEGIN CAELESTIA SETUP' "$HYPR_LUA"; then
    cat >> "$HYPR_LUA" <<'HYPRLUA'

-- BEGIN CAELESTIA SETUP
hl.on("hyprland.start", function()
    hl.exec_cmd("caelestia shell -d")
end)
-- END CAELESTIA SETUP
HYPRLUA
    ok 'Добавлен автозапуск Caelestia в hyprland.lua.'
  else info 'Блок автозапуска Caelestia уже присутствует в hyprland.lua.'; fi
elif [[ -f "$HYPR_CONF" ]]; then
  if ! grep -Fq '# BEGIN CAELESTIA SETUP' "$HYPR_CONF"; then
    cat >> "$HYPR_CONF" <<'HYPR'

# BEGIN CAELESTIA SETUP
exec-once = caelestia shell -d
# END CAELESTIA SETUP
HYPR
    ok 'Добавлен автозапуск Caelestia в hyprland.conf.'
  else info 'Блок автозапуска Caelestia уже присутствует.'; fi
else
  warn 'Не найден hyprland.lua или hyprland.conf; автозапуск не добавлен в неизвестный конфиг.'
fi

# XDG autostart — дополнительная совместимость. Основной запуск для Hyprland
# остаётся в его конфиге, если он существует.
cat > "$HOME/.config/autostart/caelestia.desktop" <<'DESKTOP'
[Desktop Entry]
Type=Application
Name=Caelestia Shell
Exec=caelestia shell -d
OnlyShowIn=Hyprland;
Hidden=false
X-GNOME-Autostart-enabled=true
DESKTOP
cat > "$HOME/.local/bin/restart-caelestia.sh" <<'RESTART'
#!/usr/bin/env bash
set -euo pipefail
command -v caelestia >/dev/null 2>&1 || { echo 'Команда caelestia не найдена; проверьте caelestia-cli.' >&2; exit 1; }
caelestia shell -k >/dev/null 2>&1 || true
sleep 1
exec caelestia shell -d
RESTART
chmod +x "$HOME/.local/bin/restart-caelestia.sh"
ok 'Созданы autostart и скрипт перезапуска Caelestia.'

for service in NetworkManager bluetooth; do
  if systemctl list-unit-files "${service}.service" --no-legend 2>/dev/null | grep -q "${service}.service"; then
    sudo systemctl enable "${service}.service"
  fi
done

# Не ломаем существующий экран входа. Включаем SDDM только если ещё не выбран
# другой display manager и пользователь явно согласен.
if systemctl is-enabled --quiet display-manager.service 2>/dev/null; then
  DM_TARGET="$(readlink -f /etc/systemd/system/display-manager.service 2>/dev/null || true)"
  if [[ "$DM_TARGET" == *sddm.service ]]; then ok 'SDDM уже выбран как экран входа.'
  else warn "Уже выбран другой display manager ($DM_TARGET); не переключаем его автоматически."; fi
else
  read -r -p 'Включить SDDM как экран входа? [y/N] ' enable_sddm
  if [[ "$enable_sddm" =~ ^[YyДд]$ ]]; then sudo systemctl enable sddm.service; ok 'SDDM включён.'
  else warn 'SDDM оставлен выключенным; текущий экран входа не менялся.'; fi
fi

# Применяем тему SDDM только если она действительно установлена.
if [[ -d /usr/share/sddm/themes/caelestia ]]; then
  sudo mkdir -p /etc/sddm.conf.d
  if sudo test -f /etc/sddm.conf.d/caelestia.conf; then sudo cp -a /etc/sddm.conf.d/caelestia.conf "/etc/sddm.conf.d/caelestia.conf.bak.$STAMP"; fi
  printf '[Theme]\nCurrent=caelestia\n' | sudo tee /etc/sddm.conf.d/caelestia.conf >/dev/null
  ok 'Включена тема SDDM Caelestia.'
else warn 'Отдельная тема SDDM Caelestia не найдена; оболочка Caelestia и экран входа — разные компоненты.'; fi

if command -v caelestia >/dev/null 2>&1; then
  info 'Caelestia CLI доступен:'
  caelestia --version 2>/dev/null || true
else warn 'Команда caelestia не найдена в PATH. Проверьте установку CLI.'; fi

echo
echo '=================================================='
echo ' УСТАНОВКА CAELESTIA ЗАВЕРШЕНА'
echo '=================================================='
echo 'Проверка пакетов: bash install-caelestia.sh --check'
echo 'Перезапуск оболочки: ~/.local/bin/restart-caelestia.sh'
echo "Резервные копии: $BACKUP_DIR"
echo "Лог: $LOG"
echo 'После проверки перезагрузитесь: sudo reboot'
echo 'На экране входа выберите Hyprland.'
echo '=================================================='
